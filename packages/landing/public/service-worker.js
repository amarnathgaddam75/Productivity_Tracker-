// The mobile PWA used to live at the site root. It now lives under /app, so
// this worker replaces the old root one, removes itself and reloads open tabs
// so visitors see the landing page instead of a stale cached app shell.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.map((k) => caches.delete(k)));
      await self.registration.unregister();
      const clients = await self.clients.matchAll({ type: 'window' });
      clients.forEach((c) => c.navigate(c.url));
    })(),
  );
});
